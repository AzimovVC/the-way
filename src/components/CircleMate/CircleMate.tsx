import type { CircleRowState } from '../../social/circles'
import type { Person } from '../../social/types'
import Avatar from '../Avatar'
import Icon from '../Icon'

interface CircleMateProps {
  partner: Person
  state: CircleRowState
  /** Она освободила этот день заморозкой. С отметкой не совпадает: строка одна на день. */
  excused?: boolean
  /** Твоя галочка стоит, но строка ждёт её ответа — режим «только вместе». */
  pending?: boolean
}

/**
 * Её место в строке — **сиденье**: круг её размера, который стоит всегда, пустой он или занятый.
 *
 * Отсюда и вся вещь. Раньше её половина была аватаром 28px, притушенным до 45%, пока она не
 * отметилась, — то есть самым заметным в общей привычке было **то, чего нет**, а сама привычка
 * отличалась от обычной значком сбоку. Сиденье того же размера, что твоя клетка, говорит «вас
 * двое» раньше, чем прочитано название.
 *
 * Стоит **справа от названия, отдельной вещью**, а не второй клеткой слева от него. Слева живёт
 * твоя галочка — то, что ты нажимаешь, — и вторая клетка рядом читалась бы как «два из двух», то
 * есть как счётчик внутри задачи. `isDone` двоичное, и «наполовину выполненной» задачи здесь не
 * заводится: твоя строка закрыта тогда, когда закрыл её ты. Форма это и держит: **человек в этом
 * приложении всегда круг** — аватар, лицо в ленте, день на дороге, — а твоя галочка квадратная.
 * Две разные формы по концам строки не складываются в ряд, который считают.
 *
 * **Плинта у сиденья нет.** Плинт в этом приложении значит «нажми меня», а нажать за неё нельзя:
 * кнопка, которая ничего не делает, — худшее, чем можно ответить на первый тап.
 *
 * Не отметилась — кольцо тихое, а лицо приглушено. Ни креста, ни минуса: «ещё не отметилась» и
 * «не сделала» — разные новости, а до конца дня правда всегда первая. Приложение, натравливающее
 * одного человека на другого, начинается ровно с этого знака.
 *
 * **Заморозилась — луна.** Это третье состояние, а не оттенок второго: «ещё не отметилась» до конца
 * дня может стать галочкой, а освобождённый день уже никогда — он честно закрыт, и общий счёт идёт
 * дальше именно поэтому. Одинаковый тихий круг на оба случая оставлял бы человека гадать, почему
 * «вместе N дней» не порвалось, — то есть прятал бы причину там, где она и есть весь ответ.
 *
 * Знак — та же луна и тот же `--color-freeze`, что у заморозки везде. Второй знак для того же
 * смысла стоил бы дороже любой картинки, а этот человек уже знает: он видел его на своём дне.
 *
 * **Ждём — пунктир**, и он на сиденье, а не на строке: ждут её, а не строку. Это единственное
 * состояние, которое приходит от режима «только вместе», и стоит оно там же, куда в этот момент
 * смотрят.
 *
 * **Лицо не уходит даже тогда, когда она отметилась.** Залить сиденье золотом было бы проще, но
 * это значит убрать человека ровно в ту минуту, ради которой пара и заведена. То же правило, по
 * которому в ленте под числом сердец стоят лица, а не голое число.
 *
 * Подпись — «Лена: отмечено», а не «Лена отметилась»: глагол в русском выдаёт род, а его человек
 * здесь нигде не называл. Имя он написал сам, какое захотел, включая «kate» и «Мама».
 */
export default function CircleMate({ partner, state, excused = false, pending = false }: CircleMateProps) {
  const done = state === 'both' || state === 'them'
  // Подпись без глагола: он в русском выдаёт род, а его человек здесь нигде не называл.
  // «Заморозка» — существительное, и поэтому годится там, где «заморозилась» не годится.
  const said = done ? 'отмечено' : excused ? 'заморозка' : pending ? 'ждём' : 'пока нет'
  const marked = done || excused

  // Пунктир носит только пустое сиденье: ответившей ждать уже нечего.
  const waiting = pending && !marked
  const ring = done
    ? 'var(--color-day-gold)'
    : excused
      ? 'var(--color-freeze)'
      : waiting
        ? 'var(--color-day-gold)'
        : 'var(--ink-500)'

  return (
    <span
      className="relative flex shrink-0 items-center pr-3"
      aria-label={`${partner.name}: ${said}`}
      title={`${partner.name}: ${said}`}
    >
      <span
        className="grid size-8 place-items-center rounded-full border-2"
        style={{ borderColor: ring, borderStyle: waiting ? 'dashed' : 'solid' }}
      >
        <Avatar name={partner.name} size={22} className={marked ? undefined : 'opacity-50'} />
      </span>
      {marked && (
        <span
          className="absolute bottom-0 right-2 grid size-[15px] place-items-center rounded-full"
          style={{
            backgroundColor: done ? 'var(--color-day-gold)' : 'var(--color-freeze)',
            boxShadow: '0 0 0 2px var(--color-surface-raised)',
          }}
          aria-hidden
        >
          <Icon
            name={done ? 'check' : 'moon'}
            size={10}
            color={done ? 'var(--color-text-on-brand)' : 'var(--color-text-primary)'}
          />
        </span>
      )}
    </span>
  )
}
