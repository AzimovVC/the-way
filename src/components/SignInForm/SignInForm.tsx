/**
 * Дверь одна, и это Google.
 *
 * **Почта и пароль отсюда убраны целиком** — решение переменено нарочно, вместе с тем, что было.
 * Здесь стояли три двери: пароль, код из письма и Google. Первые две держались на письмах, а
 * письмо — это отдельный отправщик, свой домен, записи DNS, шаблоны с `{{ .Token }}` и лимиты; и
 * пока домена нет, письма уходят **только** на почту владельца аккаунта у отправщика. То есть
 * две трети дверей в приложении не открывались никому, кроме нас, и чинилось это не кодом.
 *
 * Google при этом не просто третий способ, а другой по устройству: у него нет развилки «новый
 * или вернувшийся» — он знает это сам, — нет пароля, который забывают, нет письма, которое не
 * дошло, и нет подтверждения адреса. Всё, что мы писали вокруг почты, существовало ради вещей,
 * которых у него просто нет.
 *
 * Цена названа честно и она не нулевая: **человек без Google-аккаунта внутрь не попадёт**. Это
 * приемлемо ровно до App Store — там правило 4.8 потребует рядом Sign in with Apple, и тогда
 * дверей снова станет две. Но обе будут провайдерами, а не письмами.
 */
export default function SignInForm() {
  const { error, signInWithGoogle } = useAuth()
  const [busy, setBusy] = useState(false)

  return (
    <div className="flex flex-col gap-4">
      <button
        type="button"
        onClick={() => {
          // Удачный вызов **уводит со страницы**, и `busy` снимать некому и незачем: следующий
          // кадр этого приложения случится уже после возвращения. Снимается он только на беде —
          // когда уйти не вышло и человек остался здесь, перед той же кнопкой.
          setBusy(true)
          void signInWithGoogle().then(() => setBusy(false))
        }}
        disabled={busy}
        className="sk-btn sk-btn-outline sk-press sk-btn-block flex items-center justify-center gap-2"
      >
        <GoogleMark />
        {busy ? 'Открываю…' : 'Войти через Google'}
      </button>

      {error && (
        <p className="text-[13px]" style={{ color: 'var(--color-day-red)' }}>
          {error}
        </p>
      )}
    </div>
  )
}
