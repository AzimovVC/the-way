import SignInForm from '../SignInForm'
import { useAuth } from '../../supabase/authState'

/**
 * Дверь на социальных экранах для того, кто ещё не вошёл.
 *
 * Стоит **на месте содержимого**, а не перед ним: список друзей у невошедшего не пустой, его
 * просто нет — спросить о нём некого. Раньше эти экраны писались на заглушке, отвечавшей всем, и
 * невошедший получал «Не получилось загрузить. Проверь связь» — то есть неправду про сеть, из-за
 * которой человек шёл чинить wi-fi.
 *
 * Форма здесь целиком, а не ссылка в настройки: это ровно то место, где просить вход и надо —
 * человек пришёл за конкретной вещью и видит, за какой. Отправленный в настройки возвращается
 * сам, и половина не возвращается.
 *
 * Состояний три, потому что у сессии их три (`AuthStatus`): она поднимается с диска асинхронно, и
 * экран с двумя состояниями в первый кадр после запуска показывает вошедшему человеку «Войди».
 */
export default function SocialSignIn({ reason }: { reason: string }) {
  const { configured, status } = useAuth()

  if (!configured) {
    // Сервера нет ни у кого — вход тут не при чём, и предлагать его значило бы звать в дверь,
    // за которой ничего не построено.
    return (
      <p className="text-[13px] text-text-muted">
        Сервер ещё не подключён, и друзей здесь пока нет. Дорога работает как раньше — она лежит на
        этом телефоне.
      </p>
    )
  }

  if (status === 'loading') return <p className="text-[13px] text-text-muted">Загружаю…</p>

  return <SignInForm intro={<p className="text-[13px] text-text-secondary">{reason}</p>} />
}
