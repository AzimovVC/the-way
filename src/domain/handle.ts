/**
 * Никнейм — единственное имя, которым человека зовут **чужие**. Собственное имя на профиле он
 * пишет как хочет, хоть пустым; ник обязан быть один на весь мир, писаться в ссылку и набираться
 * в поиске с чужой клавиатуры. Отсюда всё остальное в этом файле: латиница, нижний регистр и
 * длина, которую можно продиктовать вслух.
 *
 * Сервера ещё нет, поэтому здесь нет и проверки занятости: занятость — вопрос ко всем
 * пользователям сразу, и ответить на него локально нельзя. Всё, что тут есть, — форма.
 */

/** Ниже этого ник не отличишь от опечатки, выше — не продиктуешь по телефону. */
export const HANDLE_MIN_LENGTH = 3
export const HANDLE_MAX_LENGTH = 20

/**
 * Кириллица в латиницу. Таблица своя, а не `normalize('NFD')`: тот снимает диакритику у
 * европейских букв и ничего не знает про «ж» и «щ», а имя «Женя» без этой таблицы превращается
 * в пустую строку и человек получает ник из одних цифр.
 */
const TRANSLIT: Record<string, string> = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'e', ж: 'zh', з: 'z', и: 'i', й: 'i',
  к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p', р: 'r', с: 's', т: 't', у: 'u', ф: 'f',
  х: 'h', ц: 'c', ч: 'ch', ш: 'sh', щ: 'sch', ъ: '', ы: 'y', ь: '', э: 'e', ю: 'yu', я: 'ya',
}

/** Что вообще может стоять в нике: латиница, цифры, подчёркивание. */
function isAllowed(char: string): boolean {
  return /[a-z0-9_]/.test(char)
}

/**
 * Приводит написанное человеком к тому, что можно хранить: нижний регистр, транслит, всё
 * остальное — в подчёркивание. Обрезка по длине здесь же, чтобы поле ввода не давало набрать
 * то, что потом молча укоротится.
 */
export function normalizeHandle(raw: string): string {
  let out = ''
  for (const char of raw.trim().toLowerCase()) {
    const latin = TRANSLIT[char] ?? char
    for (const letter of latin) {
      if (isAllowed(letter)) out += letter
      else if (out.length > 0 && !out.endsWith('_')) out += '_'
    }
  }
  // Хвостовое подчёркивание остаётся от пробела в конце и ничего не значит.
  while (out.endsWith('_')) out = out.slice(0, -1)
  return out.slice(0, HANDLE_MAX_LENGTH)
}

/**
 * Почему такой ник не годится, словами для экрана, или null. Пустую строку эта функция считает
 * ошибкой — но экран спрашивает про неё раньше: «ничего не ввёл» и «ввёл плохое» — разные
 * состояния поля, и второе не должно загораться, пока человек не начал печатать.
 */
export function handleProblem(handle: string): string | null {
  if (handle.length === 0) return 'Ник не может быть пустым'
  if (handle.length < HANDLE_MIN_LENGTH) return `Минимум ${HANDLE_MIN_LENGTH} символа`
  if (/^[0-9_]+$/.test(handle)) return 'Хотя бы одна буква'
  return null
}

/**
 * Ник, подобранный по имени. Он **подсказка, а не бронь**: пока сети нет, занять его не у кого,
 * и человек волен переписать его в настройках. Хвост из `seed` — это id пользователя, то есть
 * единственное, что у него уже есть уникального; без хвоста два Сергея получили бы один ник и
 * узнали бы об этом в день, когда сервер откажет обоим.
 */
export function suggestHandle(name: string, seed: string): string {
  const base = normalizeHandle(name)
  const tail = normalizeHandle(seed).replace(/_/g, '').slice(0, 4) || '0000'
  if (base.length === 0) return `way_${tail}`
  return `${base.slice(0, HANDLE_MAX_LENGTH - tail.length - 1)}_${tail}`
}

/** Как ник выходит на экран. Собачка живёт здесь, а не в разметке: её пишут в семи местах. */
export function formatHandle(handle: string): string {
  return `@${handle}`
}

/**
 * Ник человека для экрана. У записей, сделанных до ников, поля просто нет — им подбирается
 * подсказка на лету, и записывается она только тогда, когда человек её увидел и оставил или
 * поправил сам. Молча дописать ник в чужое состояние значит выдать подсказку за выбор.
 */
export function handleOf(user: { id: string; name: string; handle?: string }): string {
  return user.handle ?? suggestHandle(user.name, user.id)
}
