/**
 * Ключ новой вещи.
 *
 * Функция в одну строку существует ради **места вызова**, а не ради самой строки. Раньше ключи
 * рождались внутри правил: `addChore` сама звала `crypto.randomUUID()`, и из-за этого операция
 * «завести дело "Забрать посылку" на 19 сентября» не была вещью целиком — половина её, имя нового
 * дела, придумывалась уже внутри, в момент применения.
 *
 * Пока устройство одно, разницы нет. Как только их два — а общая привычка это ровно два
 * устройства, — та же операция, применённая у обоих, заведёт **две разные вещи** с одинаковым
 * названием. То же самое ломает и повтор списка действий: проиграв его заново, получишь другую
 * историю, хотя действия те же. Ровно по этой причине `applyAction` не смотрит на часы сам, а
 * принимает `now` аргументом; ключ — вторая половина того же правила.
 *
 * Поэтому ключ приезжает **вместе с действием**: его чеканит тот, кто действие составил, один раз.
 * Отсюда же следует, что в тестах он просто пишется руками — и они от этого читаются лучше.
 *
 * Что ещё чеканится внутри и почему это следующая правка: **`DayTask.id`**. Строка дня — не
 * названная человеком вещь, а производная: она появляется сама, когда привычка попала на день.
 * Опознают её везде — в вехах, во времени суток, в правке расписания — по паре «день + привычка»,
 * и случайный ключ рядом с этой парой уже сейчас второй ответ на один вопрос. Правильный шаг не
 * «передать ключ снаружи», а **убрать поле**: `dayId` плюс `taskTemplateId` и есть её имя.
 */
export function newId(): string {
  // `crypto.randomUUID` живёт **только в защищённом контексте**: по HTTPS и на `localhost`.
  // Приложение, открытое по адресу вида `http://192.168.1.12:5173` — то есть с телефона, из своей
  // же сети, единственным способом посмотреть PWA на живом устройстве, — таким контекстом не
  // считается, и вызов не просто отдаёт другой ключ, а **падает**: `crypto.randomUUID is not a
  // function` на первом же кадре, чёрный экран вместо двери. Проверка стоит здесь, потому что
  // здесь единственное место, где ключ рождается.
  if (typeof crypto.randomUUID === 'function') return crypto.randomUUID()

  // `getRandomValues` защищённого контекста не требует, поэтому тот же UUID собирается руками:
  // шестнадцать случайных байт, версия `4` и вариант `10xx` на своих местах. Случайность та же —
  // это тот же системный генератор, — меняется только обёртка вокруг него.
  const bytes = crypto.getRandomValues(new Uint8Array(16))
  bytes[6] = (bytes[6] & 0x0f) | 0x40
  bytes[8] = (bytes[8] & 0x3f) | 0x80
  const hex = Array.from(bytes, (b) => b.toString(16).padStart(2, '0')).join('')
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`
}
