/**
 * Когда внутри дня человек собирается это делать — утро, день, вечер.
 *
 * Три слова, а не часы, и это главное решение здесь. Точный час на привычке читается как
 * обещание: поставил 8:00, отметил в 9:10 — и приложение как будто знает, что ты опоздал.
 * А оно не знает и знать не должно: время в этом приложении ни во что не идёт (timeOfDay.ts
 * читает часы задним числом и сам говорит, что это описание). «Утром» опоздать нельзя.
 *
 * Поэтому здесь нет и не должно быть ничего, что смотрит в `partOfDay` при подсчёте:
 * ни `colorTier`, ни `pathAngleDelta`, ни веха, ни серия. Это порядок в списке дня и —
 * когда появятся пуши — то, к какому часу из настроек привязать напоминание.
 */
export type PartOfDay = 'morning' | 'day' | 'evening'

/** Порядок внутри дня, он же порядок кнопок в выборе. */
export const PARTS_OF_DAY: PartOfDay[] = ['morning', 'day', 'evening']

/**
 * `label` — на кнопке выбора («Утром»), `group` — заголовком над списком дня («Утро»).
 * Слова разные, потому что кнопка отвечает на «когда?», а заголовок называет отрезок дня.
 */
export const PART_OF_DAY: Record<PartOfDay, { label: string; group: string; hint: string; emoji: string }> = {
  morning: { label: 'Утром', group: 'Утро', hint: 'пока день не начался', emoji: '🌅' },
  day: { label: 'Днём', group: 'День', hint: 'между делами', emoji: '☀️' },
  // Вечер — закат, а не луна. Луна в этом приложении уже занята заморозкой (`Icon name="moon"`,
  // `--color-freeze`), и второй смысл у того же знака стоит дороже, чем любая картинка.
  evening: { label: 'Вечером', group: 'Вечер', hint: 'когда день закрывается', emoji: '🌆' },
}

/** Заголовок для привычек, которым время не назначено. Они идут последними — их ничто не держит. */
export const ANY_TIME_GROUP = 'Когда угодно'

/** Место отрезка в дне. Без времени — в конец: это не «поздно», это «неважно». */
export function partRank(part: PartOfDay | undefined): number {
  const i = part ? PARTS_OF_DAY.indexOf(part) : -1
  return i === -1 ? PARTS_OF_DAY.length : i
}
