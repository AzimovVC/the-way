import { PART_OF_DAY, type PartOfDay } from './partOfDay'

/**
 * Час, в который телефон напомнит о привычке, — `HH:mm` по местному времени человека.
 *
 * Это **не** срок и не второе время суток. `partOfDay` отвечает на «когда я это делаю», и поэтому
 * он нарочно не час: поставил 8:00, отметил в 9:10 — и приложение будто знает, что ты опоздал.
 * Напоминание отвечает на другой вопрос — «когда мне об этом сказать», — и у него час честный,
 * потому что говорить в какую-то секунду всё равно придётся, и выбирает её человек.
 *
 * Отсюда и то, что читать его никому нельзя. Ни `colorTier`, ни `pathAngleDelta`, ни веха, ни
 * серия, ни `completionRate` в него не смотрят и смотреть не начнут: пропущенное напоминание ничем
 * не отличается от дня, в котором его не ставили, — иначе час вернулся бы в счёт с чёрного хода.
 */
export type RemindAt = string

/** Начало и конец суток на обычной шкале — граница логического дня тут ни при чём, см. ниже. */
const HH_MM = /^([01]\d|2[0-3]):([0-5]\d)$/

/**
 * Час по умолчанию для выбранного отрезка дня — и это та самая связь, которую обещал
 * [partOfDay.ts](./partOfDay.ts): человек уже сказал «вечером», и переспрашивать его цифрой
 * значит задать один вопрос дважды.
 *
 * Числа — середины отрезков, а не их края: напоминание на 6:00 у «Утром» звонило бы тем, кто в
 * это время спит, а на 11:59 — тем, у кого утро давно кончилось. Сдвинуть его можно одним тапом,
 * и в этом весь смысл умолчания: оно не угадывает, оно избавляет от решения.
 */
export const DEFAULT_REMIND_AT: Record<PartOfDay, RemindAt> = {
  morning: '08:00',
  day: '13:00',
  evening: '20:00',
}

/**
 * Час, с которого начинают, когда отрезок дня не выбран, — и у брошенной привычки только он и
 * бывает: у «не курить» нет момента внутри дня, а вечерний вопрос «как день?» у неё есть.
 */
export const FALLBACK_REMIND_AT: RemindAt = '20:00'

/** Час, который предложить, когда напоминание только что включили. */
export function defaultRemindAt(part: PartOfDay | undefined): RemindAt {
  return part ? DEFAULT_REMIND_AT[part] : FALLBACK_REMIND_AT
}

/**
 * `HH:mm` или ничего. Поле времени в браузере отдаёт пустую строку, когда его очистили, и
 * непроверенная пустая строка легла бы в состояние временем, в которое никто не звонит.
 */
export function cleanRemindAt(value: string | undefined): RemindAt | undefined {
  if (!value) return undefined
  return HH_MM.test(value) ? value : undefined
}

/** «Вечером, в 20:00» — час рядом с тем словом, из-за которого он такой. */
export function describeRemindAt(at: RemindAt, part: PartOfDay | undefined): string {
  return part ? `${PART_OF_DAY[part].label}, в ${at}` : `В ${at}`
}
