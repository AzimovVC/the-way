import type { CircleMethods } from './circles'
import type { NoticeMethods } from './notices'
import type { FriendState, Person } from './types'

/** Человек вместе с тем, в каком отношении он к тебе стоит. Экрану нужно и то, и другое всегда. */
export interface Acquaintance {
  person: Person
  state: FriendState
  /**
   * Те, с кем дружите вы оба. Считает это **та сторона** и только она: «с кем дружит он» —
   * утверждение о чужих связях, и у нас нет ни его списка друзей, ни права его спрашивать.
   *
   * Это единственное число про чужого человека, которое здесь законно. «Сколько у него друзей» —
   * популярность, шкала, на которой кто-то всегда внизу; общие друзья — не шкала, а ответ на
   * вопрос, который человек правда задаёт, глядя на незнакомый ник: кто это и откуда я его знаю.
   *
   * Необязательное: список отдаёт строку раньше, чем профиль целиком.
   */
  mutual?: Person[]
}

/**
 * Всё, что слой знает про твои связи, одним куском. Заявки разделены на пришедшие и отправленные:
 * на первые отвечают, вторые отменяют, и экран, показавший их вперемешку, поставил бы кнопку
 * «Принять» под человеком, который тебя ещё не звал.
 */
export interface FriendsView {
  friends: Person[]
  incoming: Person[]
  outgoing: Person[]
  /**
   * Заблокированные. Едут в том же виде, потому что блокировка — такое же состояние связи, как
   * остальные три, и второй запрос за ними означал бы, что после «Заблокировать» экран знает о
   * человеке меньше, чем знал секунду назад.
   *
   * На экране друзей этой полки нет и быть не может: блокировка значит «я больше его не вижу», а
   * список, показывающий заблокированных при каждом открытии, ровно этого и не делает. Полка живёт
   * в настройках — там, куда приходят нарочно.
   */
  blocked: Person[]
}

/**
 * На что можно пожаловаться.
 *
 * Список короткий, потому что короток сам список того, что человек здесь пишет: имя, ник и названия
 * привычек. Больше в этом приложении чужого текста нет — ни ленты, ни комментариев, ни фотографий, —
 * и причины, которых не может быть, в список не ставятся.
 *
 * Названия привычек названы в первой причине **поимённо**, и это не мелочь: поле названия — то же
 * самое свободное поле, в которое пишут «Бег 5 км», и приложение не предлагает вариантов и ничего
 * не проверяет. Причина, перечислившая имя и ник и умолчавшая про полку, оставляла бы единственный
 * длинный текст в приложении без единого способа на него пожаловаться.
 *
 * Пункта «другое» нет **по той же причине, по которой причина вообще спрашивается**: без строки
 * ввода он не говорит ничего, а строка ввода — это уже переписка, на которую здесь некому отвечать.
 */
export type ReportReason = 'offensive' | 'impersonation' | 'spam'

export const REPORT_REASONS: Array<{ id: ReportReason; label: string }> = [
  { id: 'offensive', label: 'Оскорбительное имя, ник или привычка' },
  { id: 'impersonation', label: 'Выдаёт себя за другого' },
  { id: 'spam', label: 'Спам или реклама' },
]

/**
 * Дверь наружу. Сети за ней пока нет — стоит заглушка на выдуманных людях, — но **форма двери уже
 * настоящая**: всё асинхронно и всё может не ответить.
 *
 * Это и есть вся причина заводить интерфейс до бэкенда. Экран, написанный на мгновенных данных,
 * не имеет ни состояния ожидания, ни состояния ошибки, и в день, когда придёт сеть, его придётся
 * переписать целиком — а переписанный экран проверяют заново весь.
 *
 * Методы кружка приезжают сюда из [mockCircles.ts](./mockCircles.ts) и стоят в этом же
 * интерфейсе: дверь наружу одна, и вторая дверь рядом означала бы, что экран, спрашивающий про
 * людей и про кружки, ждёт и ошибается двумя разными способами.
 *
 * Каждая правка возвращает **новый вид целиком**, а не «ок». Источник правды — та сторона: она
 * одна знает, что человек за секунду до этого сам отправил тебе заявку, и ответ «вы теперь друзья»
 * на твою заявку — её право. Местная догадка о результате однажды разошлась бы с ним.
 */
export interface SocialClient extends CircleMethods, NoticeMethods {
  /** Друзья и заявки. Зовётся при открытии любого социального экрана. */
  load(): Promise<FriendsView>
  /**
   * Поиск **по нику**. Имя в найденной строке стоит, но по нему не совпадают: имя не уникально,
   * различить двух тёзок нам нечем, и заявка уехала бы не туда. Пустой запрос отдаёт пусто, а не
   * всех. Того, чьего ника ты не знаешь, зовут ссылкой-приглашением.
   */
  search(query: string): Promise<Acquaintance[]>
  /** «Кого знает твой друг» — то, на что нужен настоящий граф; заглушка отдаёт выдуманных. */
  suggestions(): Promise<Acquaintance[]>
  /** Чужой профиль по нику, или null, если такого ника нет. */
  profile(handle: string): Promise<Acquaintance | null>
  request(personId: string): Promise<FriendsView>
  cancel(personId: string): Promise<FriendsView>
  accept(personId: string): Promise<FriendsView>
  decline(personId: string): Promise<FriendsView>
  remove(personId: string): Promise<FriendsView>
  /**
   * Заблокировать. Возвращает вид, как и всякая правка связей, — потому что блокировка **и есть**
   * правка связей: друг из списка пропадает в тот же момент.
   */
  block(personId: string): Promise<FriendsView>
  unblock(personId: string): Promise<FriendsView>
  /**
   * Пожаловаться. **Единственный метод, не возвращающий вид**, и это нарочно: жалоба ничего не
   * меняет в твоих связях — она уходит людям, которые будут её читать. Вернуть отсюда `FriendsView`
   * значило бы намекнуть, что жалоба что-то сделала прямо сейчас; она не делает, и экран говорит
   * это словами.
   *
   * Причина обязательна. «Пожаловаться», отправляющее один id, — кнопка, которая делает вид:
   * прочитать такую жалобу нельзя, и единственный её эффект — успокоить нажавшего.
   */
  report(personId: string, reason: ReportReason): Promise<void>
}

/**
 * Ссылка-приглашение. Не метод клиента: сети она не требует — это собственный ник человека,
 * который у него уже есть, — а ждать сервера, чтобы показать свою же строку, незачем.
 */
export function inviteLink(handle: string): string {
  const origin = typeof location === 'undefined' ? 'https://the-way.app' : location.origin
  return `${origin}/u/${handle}`
}
