import type { FeedCalendarMark } from '../domain/feed'
import type { RankId } from '../domain/ranks'
import type { Person } from './types'

/**
 * Лента: то, что случилось у друзей, и сердца — на их событиях и на твоих.
 *
 * Лента **одна**, вкладок «Ты» и «Друзья» нет. Решение владельца, и оно опирается на простое
 * наблюдение: Feed отвечает на один вопрос — «что происходит», — и человек не должен выбирать
 * вкладку, чтобы его задать. Ломалось это ровно в одном месте: своя лента уходила на месяцы назад,
 * а чужие события важны только свежие, и смешанные как есть они поставили бы её вчерашнюю ступень
 * между твоим мартом и апрелем. Ответ — одна глубина на обоих (`FEED_WINDOW_DAYS`), а не две
 * вкладки.
 *
 * Свои события сюда не приезжают. Их выводит из дороги само устройство (`buildFeed`), где они
 * богаче: с формой возвращения, с датой и с дорогой под пальцем. Спросить их у сервера значило бы
 * завести второй разбор той же истории рядом с первым, и в день, когда копия отстанет на двадцать
 * секунд своего таймера, человек увидит свою вчерашнюю жизнь.
 *
 * А сердца приезжают **и на свои тоже**: их ставит та сторона, и знать о них отсюда неоткуда.
 */

/**
 * Событие друга.
 *
 * Родов три, и каждый положителен: ступень, новая привычка, метка дороги. Это не сокращение списка
 * ради простоты — это **запрет**: наружу не уезжает ничто, что называет пропуск. Ни красных дней,
 * ни оборванных серий, ни возвращения. Возвращение существует только там, где был спад, и строка
 * «5 дней вниз, потом 3 вверх» на чужом экране рассказывает про провал человека, который его не
 * рассказывал. На своей ленте оно остаётся: там это актив, а не новость о падении.
 */
export interface FriendEvent {
  id: string
  person: Person
  date: string
  /**
   * Момент, если он у события есть, — чтобы чужая строка старела теми же словами, что своя.
   *
   * Это **не** `created_at` строки на сервере: тот говорит, когда копия доехала по таймеру, а не
   * когда с человеком случилось. Ступень, взятая в субботу и уехавшая в понедельник, сказала бы
   * «2 часа назад» про позавчера. Уезжает поэтому свой момент, и только у событий, у которых он
   * записан; у остальных его нет, и строка говорит в днях.
   */
  at?: string
  kind: 'rank' | 'goal' | 'calendar'
  /** Название привычки или цели. У метки дороги его нет — она называет себя родом. */
  title?: string
  /**
   * Ступень **словом**, хотя выводится она из дней. Лестница живёт в `ranks.ts`, и день, когда она
   * сдвинется, не имеет права переписать то, что уже случилось у человека: «Ученик» в чужой ленте —
   * запись о прошлом, а не вывод из сегодняшних правил.
   */
  rank?: RankId
  days?: number
  mark?: FeedCalendarMark
}

/**
 * Одно сердце: кто сказал его какому событию.
 *
 * Хранится строкой на человека, а не числом на событии, потому что на экране рисуется **лицо**, а
 * не счёт. Своему событию сердце поставить можно — решение владельца, принятое с названной ценой:
 * счёт стал бы накручиваемым. Лица эту цену снимают: своё лицо среди двух чужих никого не
 * обманывает, а «3» обманывает.
 */
export interface FeedHeart {
  ownerId: string
  eventId: string
  personId: string
}

export interface SocialFeed {
  events: FriendEvent[]
  hearts: FeedHeart[]
}

export interface FeedMethods {
  /** Что случилось не раньше `since` — `YYYY-MM-DD`, посчитанный `feedSince`. */
  feed(since: string): Promise<SocialFeed>
  /**
   * Сказать сердце и забрать его назад. Обе возвращают ленту **целиком**, а не «ок»: кто сказал
   * сердце этому событию, знает та сторона, и местная догадка однажды разошлась бы с ней.
   *
   * `ownerId` нужен потому, что событие зовут парой «чьё» + «какое»: имя события выводится из дня
   * и привычки (`feedEventId`), и у двоих друзей, взявших «Ученика» в один день в привычке с одним
   * ключом, оно совпало бы. Пара не совпадёт никогда.
   */
  heart(ownerId: string, eventId: string, since: string): Promise<SocialFeed>
  unheart(ownerId: string, eventId: string, since: string): Promise<SocialFeed>
}

/** Кто сказал сердце этому событию — лицами, в порядке, в котором говорили. */
export function heartsOn(feed: SocialFeed, ownerId: string, eventId: string): string[] {
  return feed.hearts
    .filter((heart) => heart.ownerId === ownerId && heart.eventId === eventId)
    .map((heart) => heart.personId)
}
