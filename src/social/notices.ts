import { formatShortDate } from '../domain/calendar'
import { getLogicalToday } from '../domain/pathEngine'

/**
 * Сообщение: то, что случилось с тобой, пока тебя тут не было.
 *
 * Механизм **общий**, а не приделанный к кружку, и род у него пока один. Это не задел на будущее:
 * первая же вещь, которой он понадобился, — выход из кружка, — сообщается **сообщением, а не
 * пропажей**, и молча исчезнувшая вторая кнопка была бы худшим
 * способом сказать такую новость.
 *
 * The mechanism has one load-bearing rule: **the server mints a notice, a person never does**.
 * Nobody has an insert policy on the table (migration 0007). A notice speaks in the app's voice
 * ("Лена больше не в общей привычке"), and a table people could write to would let anyone forge
 * that news. What one person sends another — GIFs — lives in its own table, not here.
 *
 * Отсюда два следствия, которые легко нарушить:
 *
 * - **непрочитанное — это существование строки**, а не поле «прочитано». Числа непрочитанных в
 *   приложении нет нигде: число под записью превращает записи в счёт;
 * - **сообщение не попадает в `AppState`.** Оно живёт здесь, рядом с людьми и кружками, по тому же
 *   правилу, что и всё в `src/social/`: существование другого человека не имеет права сделать тебе
 *   хуже про день, который ты уже прожил.
 */

/**
 * Род сообщения. Список закрытый нарочно — тот же, что в проверке колонки на сервере: род обязан
 * иметь свой экран, а свободная строка здесь означала бы сообщение, которое некому нарисовать.
 */
export type NoticeKind = 'circle_left'

/**
 * Второй вышел из кружка.
 *
 * Имя лежит **в самом сообщении**, а не берётся из кружка по ссылке: к моменту, когда человек
 * дочитает карточку, кружка уже может не быть, а прощаться с «кем-то» нельзя. По той же причине
 * здесь название — то самое слово, на которое соглашались, а не сегодняшнее имя твоей привычки.
 */
export interface CircleLeftNotice {
  id: string
  kind: 'circle_left'
  circleId: string
  title: string
  partnerName: string
  createdAt: string
}

export type Notice = CircleLeftNotice

/** Две ручки: спросить и закрыть. Обе отдают список целиком — правду о нём знает та сторона. */
export interface NoticeMethods {
  notices(): Promise<Notice[]>
  /**
   * Закрыть.
   *
   * У выхода из кружка это нажатие уносит и **саму запись о паре**: дочитанная карточка — конец
   * записи, а половина записи, оставшаяся лежать, однажды всплывёт строкой про человека, с которым
   * всё давно кончилось. Знает про это сервер, а не экран: закрытие — одна операция, а не две.
   */
  noticeDismiss(noticeId: string): Promise<Notice[]>
}

/**
 * Что написать на прощальной карточке.
 *
 * Фраза собирается здесь, а не приезжает с сервера: тексты правятся без миграции, и в приложении,
 * где слова — половина работы, это разница между правкой на минуту и правкой на выкатку.
 *
 * Подпись **без глагола**: «Лена больше не в общей привычке», а не «Лена вышла». Глагол в русском выдаёт
 * род, а его человек здесь нигде не называл — ровно то же правило, что у `CircleMate`.
 */
export function noticeHeadline(notice: Notice): string {
  const who = notice.partnerName.trim()
  return who === '' ? 'Общей привычки больше нет' : `${who} больше не в общей привычке`
}

/**
 * Вторая строка: что от этого меняется.
 *
 * Названа цена, и она нулевая, — потому что это и есть главная новость. Привычка остаётся обычной
 * привычкой **со всеми своими днями**: чужой уход не имеет права отобрать у человека его же жизнь.
 * Человек, увидевший «больше не в общей привычке» без этой строки, в первую секунду думает именно о том,
 * что он потерял.
 */
/**
 * Когда это случилось.
 *
 * День, а не час: «в 21:40» — точность, которой нечего делать в записи о конце пары, и она же
 * обещала бы, что приложение знает, в какую минуту человек принял решение. Оно знает только, когда
 * приехала строка.
 *
 * День **логический**, через тот же `getLogicalToday`, что и везде: сообщение, доехавшее в 02:30,
 * принадлежит закрывающемуся вечеру, а не наступившему утру. Второй ответ на вопрос «какой это был
 * день» в приложении, где день кончается в 3:00, разошёлся бы с дорогой на глазах.
 *
 * Дата стоит на карточке потому, что без неё **две пары с одним названием дают две неразличимые
 * новости**. «Зарядка» с женой и «Зарядка» с братом — вещь совершенно обычная, а карточка, у
 * которой совпали и имя, и название, читается как дубль: человек тапает «Понятно» дважды, думая,
 * что закрывает одну и ту же.
 */
export function noticeDay(notice: Notice): string {
  return formatShortDate(getLogicalToday(new Date(notice.createdAt)))
}

export function noticeReassurance(notice: Notice): string {
  return `«${notice.title}» остаётся твоей привычкой со всеми днями. Уходит только общий счёт.`
}
