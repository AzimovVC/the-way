/**
 * Люди вокруг: их формы и то, в каком отношении к тебе каждый стоит.
 *
 * **Ни одно значение отсюда не имеет права попасть в `AppState`.** Линейка для любой социальной
 * вещи в этом приложении одна: может ли существование другого человека сделать тебе хуже про день,
 * который ты уже прожил? Пока друзья живут в отдельном слое, ответ «нет» держится сам собой —
 * дороге просто нечего о них прочитать.
 */

/**
 * Одна привычка чужого человека — ровно то, что стоит на витрине, и ничего больше.
 *
 * Дни здесь есть, а ступени нет: ступень выводится из дней по той же лестнице
 * ([ranks.ts](../domain/ranks.ts)), одной на всех. Прислать её отдельным полем значило бы завести
 * второй экземпляр числа, которое уже сказано, — и в день, когда они разойдутся, «Мастер» встанет
 * над сорока днями. Лестница у обеих сторон одна, потому что это словарь приложения, а не настройка.
 *
 * Чего здесь нет: процента, серии и дат взятых ступеней. Это уже не «докуда дошёл», а разбор чужого
 * пути, и читать его должен тот, кто его прошёл.
 */
export interface PersonHabit {
  /** Ключ списка, а не ссылка: открывать у чужой привычки нечего. */
  id: string
  title: string
  /** Значок, если он у неё есть. Нет — медаль берёт букву, как и у себя. */
  icon?: string
  /** Дни, набранные привычкой. Считает их та сторона: пропуски и возвращения — её арифметика. */
  days: number
}

/** Человек, каким его видно снаружи. Всё здесь — его запись о себе, и она у него единственная. */
export interface Person {
  id: string
  /** `@ник` без собачки — см. [handle.ts](../domain/handle.ts). */
  handle: string
  name: string
  /**
   * Что видно про чужой путь: сколько дней он идёт, сколько привычек считает, какая серия сейчас.
   * Это **его** числа, посчитанные у него. Своих чисел про чужого человека мы не держим и не
   * выводим: у нас нет его дней, а угадывать по трём цифрам — это выдумывать чужую историю.
   *
   * Необязательные, потому что поиск отдаёт строку раньше, чем профиль целиком.
   */
  daysOnRoad?: number
  habitCount?: number
  currentStreak?: number
  /**
   * Витрина: его привычки со ступенями, которых они достигли. Сравнения здесь нет и быть не может —
   * это его полка, а не его половина таблицы.
   */
  habits?: PersonHabit[]
}

/**
 * В каком отношении человек стоит к тебе. Дружба **взаимная**: «отправил» и «пришла» — разные
 * состояния, и второе требует ответа. Односторонней подписки здесь нет намеренно — общая привычка
 * («смотрим сериал», «созваниваемся») законна только тогда, когда обе стороны сказали «да», и
 * слово «друг», выданное без согласия второго, обещало бы то, чего нет.
 *
 * `blocked` стоит **в этом же ряду**, а не отдельным списком рядом. Блокировка — это отношение, и
 * ряд отвечает на вопрос «кто он тебе» ровно одним значением: заведи её вторым полем, и появится
 * человек, который одновременно друг и заблокирован, — состояние, у которого нет правильного
 * экрана. Из одного ряда следует и то, что блокировка **снимает дружбу**: другого способа стоять
 * в этом ряду у неё нет, и это честнее, чем блокировка, тихо оставившая тебя в чьих-то друзьях.
 */
export type FriendState = 'none' | 'outgoing' | 'incoming' | 'friends' | 'blocked'

/**
 * То, что слой держит на диске: копия ответа сервера, а не запись человека.
 *
 * Отсюда всё поведение хранилища. Своя версия, свой ключ, и непрочитанная запись **просто
 * начинается заново** — в отличие от конверта дороги, который в таком случае уезжает в карантин.
 * Дорога — единственная копия истории, и потерять её нельзя; список друзей всегда можно спросить
 * снова у того, кто его и выдал.
 */
export interface SocialSnapshot {
  /** Все, кого слой когда-либо видел, по id. */
  people: Record<string, Person>
  /** Состояние отношений, по id человека. `none` здесь не хранится — его отсутствие и есть `none`. */
  links: Record<string, Exclude<FriendState, 'none'>>
}

export function emptySnapshot(): SocialSnapshot {
  return { people: {}, links: {} }
}
