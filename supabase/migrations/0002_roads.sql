-- Дорога в аккаунте: копия, а не переезд.
--
-- Дорога остаётся в `the-way:v1` на телефоне и остаётся источником правды — приложение PWA, и
-- день, отмеченный в метро, не имеет права потеряться. Здесь лежит то же самое, что уезжает в файл
-- резервной копии, только уезжает само (docs/circle.md, «Дорога в аккаунте»).
--
-- Порядок в файле тот же, что в 0001, и по той же причине: таблица, `enable row level security`,
-- политика — до первой строки. Ключ у клиента публичный, и данные защищают только политики.
--
-- Файл запускается повторно без вреда.

create table if not exists public.roads (
  -- Одна дорога на человека, и первичный ключ это и говорит. Второй телефон не заводит вторую
  -- строку: он либо забирает эту, либо спрашивает — слияние двух историй сейчас не делается, а
  -- строка на устройство означала бы, что оно уже как-то случилось.
  user_id uuid primary key references auth.users on delete cascade,

  -- Версия конверта **колонкой**, хотя она же лежит внутри `state`. Так «какие записи ещё на v4»
  -- это запрос, а не выгрузка всей базы на чей-то ноутбук.
  version int not null check (version >= 1),

  -- Конверт целиком — ровно то, что читает `readEnvelope`. Год истории с тремя привычками ≈ 150 КБ.
  -- Не разобран на колонки нарочно: разбор здесь означал бы вторую модель данных рядом с
  -- `models.ts`, которую придётся мигрировать второй цепочкой.
  state jsonb not null,

  updated_at timestamptz not null default now()
);

alter table public.roads enable row level security;

-- Самое сильное правило приложения, какое можно записать схемой: чужую дорогу не читает **никто**,
-- включая друзей. Одна политика `for all` вместо четырёх — потому что условие у всех четырёх
-- одно и то же, и разложенное на четыре копии оно однажды разъедется в одной из них.
--
-- `with check` здесь не дубль `using`: без него вошедший мог бы записать строку на чужой `user_id`.
drop policy if exists "своя дорога" on public.roads;
create policy "своя дорога"
  on public.roads for all
  to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

-- `touch_updated_at` заведена в 0001; здесь она только вешается на вторую таблицу. Время ставит
-- сервер, а не клиент: «что новее» решается по этой колонке, а часы на телефоне переводит кто угодно.
drop trigger if exists roads_touch_updated_at on public.roads;
create trigger roads_touch_updated_at
  before update on public.roads
  for each row execute function public.touch_updated_at();
