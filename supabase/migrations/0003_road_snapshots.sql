-- Что аккаунт помнил вчера.
--
-- В `roads` одна строка на человека, и каждая выгрузка её затирает. Пока дорога цела на телефоне,
-- это нормально — там источник правды. Но ровно тот случай, ради которого аккаунт и заведён (телефон
-- потерян, данные очищены, PWA выселена), оставляет одну-единственную копию, и любая беда, успевшая
-- уехать в неё раньше, чем человек заметил, необратима. Файл резервной копии здесь не помогает: его
-- никто не делает.
--
-- Поэтому у аккаунта появляется короткая память: по одному снимку на день, `SNAPSHOT_KEEP_DAYS`
-- дней назад. Клиент про неё не знает и ничего лишнего не отправляет — снимок делает сам сервер из
-- той строки, которую собирается заменить.
--
-- Порядок в файле тот же, что в 0001 и 0002: таблица, `enable row level security`, политика — до
-- первой строки. Файл запускается повторно без вреда.

create table if not exists public.road_snapshots (
  user_id uuid not null references auth.users on delete cascade,

  -- День сервера, а не логический день человека. Это **ярлык на копии**, а не запись о дне: по нему
  -- выбирают, к какому числу вернуться, и сутки туда-сюда этому выбору не мешают. Логический день
  -- (граница в 3:00 местного) живёт внутри самого конверта, где он и нужен.
  taken_on date not null,

  version int not null check (version >= 1),
  state jsonb not null,

  -- Чем эта дорога кончалась, вынуто из конверта при записи. Нужно ровно для списка: человек
  -- выбирает, к чему вернуться, по «34 дня, последний — 11 окт», а не по дате снимка. Дата снимка
  -- для этого не годится и врала бы на сутки — снимок за 12-е хранит то, чем аккаунт кончил 11-е.
  -- Тянуть ради подписи по 150 КБ на строку списка нельзя, а сервер это уже держит в руках.
  day_count int not null default 0 check (day_count >= 0),
  last_date text,

  -- Когда снимок на самом деле лёг. Отличается от `taken_on` ровно тем, что `taken_on` — ключ.
  created_at timestamptz not null default now(),

  -- Один снимок на день, и это первичный ключ, а не индекс: второй снимок того же дня не «ещё
  -- одна запись», а попытка переписать уже сохранённое.
  primary key (user_id, taken_on)
);

alter table public.road_snapshots enable row level security;

-- Читает только хозяин — то же самое правило, что у `roads`, и по той же причине: это его история
-- целиком. Политик на insert, update и delete нет **вовсе**, и это не забывчивость: снимки пишет
-- триггер от имени хозяина таблиц, а клиенту здесь делать нечего. Подделать снимок нельзя,
-- переписать его своим — тоже, и в этом весь смысл второй копии.
drop policy if exists "свои снимки" on public.road_snapshots;
create policy "свои снимки"
  on public.road_snapshots for select
  to authenticated
  using (auth.uid() = user_id);

-- Снимок делается **перед заменой** и хранит то, что лежало до неё.
--
-- Два решения внутри:
--
-- `on conflict do nothing`, а не «обновить». Значит снимок дня — это самая **первая** версия,
-- увиденная в этот день, то есть то, чем аккаунт кончил предыдущий. Обновляющий вариант выглядит
-- аккуратнее (в снимке лежало бы побольше истории), но он же и бесполезен: беда, уехавшая сегодня
-- в аккаунт, сегодня же переписала бы и сегодняшний снимок. Вторая копия, которую портит та же
-- запись, что и первую, — не вторая копия.
--
-- `security definer` — потому что политик на запись у таблицы нет. Функция принадлежит хозяину
-- таблиц и поэтому кладёт строку; `search_path` прибит, иначе вызывающий подставил бы свою схему.
create or replace function public.keep_road_snapshot() returns trigger
language plpgsql security definer set search_path = public, pg_temp as $$
begin
  -- `coalesce` и `->` через `->'state'`: разбирать конверт здесь нельзя (вторая модель данных
  -- рядом с models.ts — то, от чего `roads` и уклоняется), но заглянуть в две его клетки можно.
  -- Записи, у которой этих клеток нет, достанется 0 и null — подпись без числа, а не потерянный снимок.
  insert into public.road_snapshots (user_id, taken_on, version, state, day_count, last_date)
  values (
    old.user_id,
    (old.updated_at at time zone 'UTC')::date,
    old.version,
    old.state,
    jsonb_array_length(coalesce(old.state->'state'->'days', '[]'::jsonb)),
    old.state->'state'->'days'->-1->>'date'
  )
  on conflict (user_id, taken_on) do nothing;

  -- Две недели. Срок выбран по тому, за сколько человек замечает, что история не та: он открывает
  -- приложение каждый день, и «у меня пропала неделя» — это разговор того же вечера, а не через
  -- месяц. Больше держать нечем не жалко, а можно: 150 КБ на снимок, две недели — это 2 МБ на
  -- человека, и уже на десяти тысячах людей счёт идёт на десятки гигабайт.
  delete from public.road_snapshots
  where user_id = old.user_id
    and taken_on < current_date - 14;

  return null;
end;
$$;

-- `after`, а не `before`, и это не вкусовщина. У `before`-триггера возвращённое значение — это та
-- строка, которую запишут: вернув `old`, он тихо отменил бы саму выгрузку, а вернув `new`, встал бы
-- в очередь с `roads_touch_updated_at` и начал зависеть от того, чьё имя раньше по алфавиту. У
-- `after` возвращённое значение никто не смотрит, а `old` по-прежнему под рукой.
--
-- Только на update: первой в жизни выгрузке заменять нечего, и снимать там нечего тоже.
drop trigger if exists roads_keep_snapshot on public.roads;
create trigger roads_keep_snapshot
  after update on public.roads
  for each row execute function public.keep_road_snapshot();
