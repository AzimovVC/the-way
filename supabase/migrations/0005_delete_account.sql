-- Удаление аккаунта: то единственное, чего человек не может сделать сам.
--
-- Новых таблиц здесь нет, поэтому нет и строчки `enable row level security`: файл состоит из одной
-- функции. Всё, что она уносит, уносится **каскадом** — профиль, дорога, снимки, заявки, дружбы,
-- блокировки и жалобы висят на `auth.users ... on delete cascade` с первого дня, и отдельного
-- списка «что ещё удалить» здесь нет нарочно: список, который надо дописывать вручную, однажды
-- отстанет от схемы, и тогда после удаления останется строка, ссылающаяся на человека, которого
-- нет. Заводя таблицу с человеком, вешай её на `auth.users`, а не на `profiles` — и она унесётся
-- сама.
--
-- Цена названа: жалобы **на** удалившегося тоже уходят (`reports.target_id`). Пока модерации нет,
-- это честно — жаловаться больше не на кого; в тот день, когда жалобы начнут читать, они должны
-- пережить удаление, и это будет отдельное решение с отдельной колонкой, а не тихий недосмотр.
--
-- `security definer`, потому что `auth.users` клиенту не принадлежит: своей строкой в ней он не
-- распоряжается ни при каких политиках. Функция при этом не берёт аргументов и не умеет удалить
-- чужого — она знает ровно одного человека, `auth.uid()`, то есть того, кто её и позвал.

create or replace function public.delete_account() returns void
language plpgsql security definer set search_path = public, pg_temp as $$
begin
  -- Невошедшего сюда не пускает и `grant`, но проверка стоит: `delete ... where id = null` не
  -- ошибка, а удачное удаление нуля строк, и такой вызов ответил бы «готово», ничего не сделав.
  if auth.uid() is null then
    raise exception 'удалять нечего: никто не вошёл';
  end if;

  delete from auth.users where id = auth.uid();
end;
$$;

revoke execute on function public.delete_account() from public;
grant execute on function public.delete_account() to authenticated;
